"""Generate cpp/src/sqlglot_tables.inc from the installed sqlglot.

The reference policy matches on sqlglot's *canonical* function names (string_agg -> group_concat,
now -> current_timestamp, ...). Rather than guess, probe sqlglot for every known function name and
bake the result into a table. Also probes which leading keywords sqlglot turns into a generic
Command / Set / Copy ... node (all blocked by the policy) and which niladic names are functions.

Usage: uv run --no-project --with sqlglot==30.33.0 --with pydantic --with pyyaml python tools/gen_tables.py
"""

from __future__ import annotations

from pathlib import Path

import sqlglot
from ref import policy as P
from sqlglot import exp
from sqlglot.dialects.postgres import Postgres

OUT = Path(__file__).resolve().parents[1] / "cpp" / "src" / "sqlglot_tables.inc"
ARGS = ["a", "b", "c", "d"]


def probe_call(name: str, n: int) -> str | None:
    """Canonical-name list ('' = operator node only), or None when sqlglot rejects the call."""
    sql = f"SELECT {name}({', '.join(ARGS[:n])}) FROM t"
    try:
        stmts = P.parse(sql)
    except Exception:
        return None
    if len(stmts) != 1 or not isinstance(stmts[0], exp.Select):
        return None
    names = []
    for f in stmts[0].find_all(exp.Func):
        if isinstance(f, P.OPERATOR_NODES):
            continue
        names.append(P.function_name(f))
    return " ".join(names)


def candidates() -> list[str]:
    names = {k.lower() for k in exp.FUNCTION_BY_NAME}
    names |= {k.lower() for k in Postgres.Parser.FUNCTIONS}
    names |= {
        "pg_sleep",
        "pg_read_file",
        "nextval",
        "setval",
        "currval",
        "current_setting",
        "set_config",
        "dblink",
        "lo_import",
        "pg_ls_dir",
        "generate_series",
        "unnest",
        "version",
        "random",
        "string_agg",
        "to_char",
        "date_part",
        "date_trunc",
        "now",
        "age",
        "strpos",
        "regexp_matches",
        "array_length",
        "jsonb_build_object",
    }
    return sorted(n for n in names if n.replace("_", "").isalnum() and not n[0].isdigit())


def main() -> None:
    lines: list[str] = ["// GENERATED by tools/gen_tables.py from sqlglot " + sqlglot.__version__ + ". Do not edit.", ""]
    fn_rows = []
    for name in candidates():
        res = {n: probe_call(name, n) for n in range(7)}
        ok = {n: r for n, r in res.items() if r is not None}
        if not ok:
            continue
        distinct = set(ok.values())
        if distinct == {name}:
            continue  # identity for every accepted arity
        if len(distinct) == 1 and len(ok) >= 2:
            fn_rows.append((name, -1, distinct.pop()))
        else:
            fn_rows.extend((name, n, r) for n, r in ok.items() if r != name)
    # sqlglot rejects calls with the wrong number of arguments for typed functions (PARSE_ERROR in the policy).
    arity_rows = []
    for name in candidates():
        ok = [n for n in range(7) if probe_call(name, n) is not None]
        if 0 < len(ok) < 7:
            arity_rows.append((name, sum(1 << n for n in ok)))
    lines.append("inline constexpr FunctionArity kFunctionArity[] = {")
    lines += [f'    {{"{n}", {m}}},' for n, m in arity_rows]
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr FunctionCanon kFunctionCanon[] = {")
    lines += [f'    {{"{n}", {a}, "{c}"}},' for n, a, c in fn_rows]
    lines.append("};")
    lines.append("")

    nil = []
    for name in [
        "current_date",
        "current_time",
        "current_timestamp",
        "localtime",
        "localtimestamp",
        "current_user",
        "session_user",
        "user",
        "current_role",
        "current_schema",
        "current_catalog",
        "current_database",
    ]:
        stmts = P.parse(f"SELECT {name}")
        node = stmts[0].expressions[0]
        if isinstance(node, exp.Func):
            nil.append(f'    {{"{name}", "{P.function_name(node)}"}},')
    lines.append("inline constexpr NiladicFunc kNiladic[] = {")
    lines += nil
    lines.append("};")
    lines.append("")

    words = []
    for w in [
        "SET",
        "COPY",
        "BEGIN",
        "START",
        "COMMIT",
        "END",
        "ROLLBACK",
        "ABORT",
        "USE",
        "VACUUM",
        "EXPLAIN",
        "ANALYZE",
        "SHOW",
        "LOCK",
        "CALL",
        "DO",
        "LISTEN",
        "NOTIFY",
        "REFRESH",
        "REINDEX",
        "CLUSTER",
        "DISCARD",
        "PREPARE",
        "EXECUTE",
        "DEALLOCATE",
        "RESET",
        "FETCH",
        "MOVE",
        "CLOSE",
        "DECLARE",
        "CHECKPOINT",
        "SAVEPOINT",
        "RELEASE",
        "UNLISTEN",
        "LOAD",
        "SECURITY",
        "IMPORT",
        "MERGE",
        "REASSIGN",
        "ABORT",
    ]:
        try:
            stmts = P.parse(f"{w} x")
        except Exception:
            continue
        if len(stmts) == 1:
            words.append(f'    {{"{w}", "{type(stmts[0]).__name__}"}},')
    lines.append("inline constexpr StatementWord kStatementWords[] = {")
    lines += sorted(set(words))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(fn_rows)} function rows, {len(nil)} niladic, {len(set(words))} statement words")


if __name__ == "__main__":
    main()
